/**-------------------------------------------------------------------------------------------------------------------
* 
* @fn         bool XSTRING::DeleteLastZeros()
* @brief      Delete Last Zeros
* @ingroup    XUTILS
* 
* @return     bool : true if the operation is successful; otherwise false.
* 
* --------------------------------------------------------------------------------------------------------------------*/
bool XSTRING::DeleteLastZeros()
{
  int  index  = GetSize() - 1;
  bool status = false;

  if(index <= 0)
    {
      return false;
    }

  if(FindCharacter(_C('.')) < 0)  
    {
      return false;                                // integer: no fractional zeros to trim
    }

  while(Character_GetLast() == _C('0'))
    {
      DeleteLastCharacter();
      status = true;
    }

  if(Character_GetLast() == _C('.'))             // drop a dangling decimal point
    {
      DeleteLastCharacter();
      status = true;
    }

  return status;
}


