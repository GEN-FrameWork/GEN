{
  xbuffer.Delete();

  for(int c=0; c<(int)GetSize(); c+=2)
    {
      XCHAR    hexbytechar[3] = { 0, 0, 0 };
      XSTRING  hexbytestr;
      int      data;

      hexbytechar[0] = Get()[c];
      hexbytechar[1] = Get()[c+1];

      hexbytestr = hexbytechar;

      hexbytestr.UnFormat(_L("%02X"), &data);
      xbuffer.Add((XBYTE)data);
    }

  return true;
}


