              case XSTRINGASCIICODE_ISO_8859_1   : asciicharacter = asccicodeentrys[c].iso88591;      break;
              case XSTRINGASCIICODE_ISO_8859_2   : asciicharacter = asccicodeentrys[c].iso88592;      break;
              case XSTRINGASCIICODE_ISO_8859_3   : asciicharacter = asccicodeentrys[c].iso88593;      break;
              case XSTRINGASCIICODE_ISO_8859_4   : asciicharacter = asccicodeentrys[c].iso88594;      break;
