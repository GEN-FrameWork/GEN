/**-------------------------------------------------------------------------------------------------------------------
* 
* @fn         bool XSTRING::ConvertHexFormatChars()
* @brief      Convert hex format chars
* @ingroup    XUTILS
* 
* @return     bool : true if the operation is successful; otherwise false.
* 
* --------------------------------------------------------------------------------------------------------------------*/
bool XSTRING::ConvertHexFormatChars()
{
  XSTRING string;

  string.Empty();

  if(IsEmpty()) return false;

  for(int c=0;c<(int)GetSize();c++)
    {
      XCHAR character[3] = { 0 , 0 , 0 };

      character[0] = Get()[c];
      character[1] = Get()[c+1];

      if((character[0]==_C('\\')) && (character[1]==_C('x')))
        {
          XSTRING   numberhex;
          XCHAR part[2] = { 0 , 0 };

          c+=2;

          for(int d=0;d<2;d++)
            {
              part[0] = Get()[c+d];
              numberhex.Add(part);
            }

          numberhex.UnFormat(_L("%02X"), &part[0]);

          part[0]&=0x00FF;
          string.Add(part);

          c++;
        }
       else string.Add((XCHAR)character[0]);
    }

  if(string.IsEmpty()) return false;

  Set(string);

  return true;
}


